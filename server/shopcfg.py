def refresh_stale_names(data_dir=None, apply=False):
    """把**出厂名改过、而运营没动过**的那几件物品刷成新的出厂名。

    返回 `[(itemId, 盘上的旧名, 新名)]`；`apply=False`（默认）只算不写。

    ★★ **判据是「盘上那个名字还等于我们当初发出去的那个」** ——
    运营自己改过的名字**一个都不碰**（铁律 11）。这不是「拿默认值盖掉用户的
    设置」，是「这一格他从来没碰过，而我们换了出厂值，替他带过去」。

    ★ 这条判据**自带幂等**：刷完之后盘上的名字已经不等于旧名了，
    再跑一遍就是空的。⇒ 它不需要「跑过没有」的标记。
    ⚠ 唯一的边角：运营**手工把名字改回旧的出厂名**，那下次还会被刷走。
      真遇到了让他改成别的写法（比如「厄运卡片 」带个空格）——
      为这种情况再养一份迁移记录不值当。

    ★ 写盘那一路和别处完全一样：先留 `*.bak-<时刻>`、过 `validate_items`、
      拿和管理页保存 / 数据备份**同一把写锁**。
    """
    path = path_of(ITEMS_FILENAME, data_dir)
    if not os.path.exists(path):
        return []                       # 没有就该由 `ensure_files` 去生成
    try:
        with open(path, "r", encoding="utf-8") as fp:
            raw = json.load(fp)
    except (OSError, ValueError):
        return []                       # 读不懂就别动它（D10）
    entries = raw.get("items")
    if not isinstance(entries, list):
        return []
    import shopdefaults
    changed = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        try:
            item_id = int(entry.get("id"))
        except (TypeError, ValueError):
            continue
        was = RENAMED_DEFAULT_NAMES.get(item_id)
        if was is None or entry.get("name") != was:
            continue                    # 不在表里 / 运营改过了 -> 不碰
        item = shopdata.get(item_id)
        now = shopdefaults.name_of(item) if item is not None else None
        if not now or now == was:
            continue                    # 设计表里也没换 -> 没事可做
        changed.append((item_id, was, now))
        if apply:
            entry["name"] = now
    if not (apply and changed):
        return changed
    validate_items(raw)                 # 宁可什么都不写，也不写一份读不了的
    with write_lock(ITEMS_FILENAME):
        shutil.copyfile(path, "%s.bak-%s"
                        % (path, time.strftime("%Y%m%d-%H%M%S")))
        write_json(path, raw)
    invalidate(data_dir)
    return changed


def backfill_defaults(data_dir=None, apply=False, only=None):
    """把默认表里有、现有文件里**没有**的条目补进去。返回 `{文件名: [新条目]}`。

    `only` 给一组文件名时只看那几份（管理页上那颗「补齐默认值」按钮
    是按页给的，一次只补当前这一页那一份）。

    ★ **只增不改**：已经在文件里的条目一个字节都不动（用户改过的价格 /
    花费 / 上架开关全部原样留着，铁律 11）。**幂等** —— 补完再跑一次是空的。

    ★ 为什么需要它：`ensure_files` 只在文件**不存在**时生成一份（D7），
    所以「我们后来发现少收了一批物品」这种事没有别的出口。
    2026-09-05 就撞上一次：`PART_SUFFIX_ZH` 漏了 `바지` / `신발`，
    泰尔的四条下装和四双鞋从来没进过默认配方。

    `apply=False`（默认）只算不写 —— 先看清楚要加什么再决定。
    真写的时候先把原文件复制一份 `*.bak-<时刻>` 放在旁边。
    """
    added = {}
    for filename, (list_key, id_key) in BACKFILL_KEYS.items():
        if only is not None and filename not in only:
            continue
        path = path_of(filename, data_dir)
        if not os.path.exists(path):
            continue                    # 没有就该由 `ensure_files` 去生成
        try:
            with open(path, "r", encoding="utf-8") as fp:
                raw = json.load(fp)
        except (OSError, ValueError):
            # 读不了就跳过。**绝不拿默认值盖掉一份读不懂的文件**（D10）。
            continue
        entries = raw.get(list_key)
        if not isinstance(entries, list):
            continue
        have = set()
        for entry in entries:
            if isinstance(entry, dict) and entry.get(id_key) is not None:
                have.add(int(entry[id_key]))
        build = _SPECS[filename][1]
        fresh = [entry for entry in build().get(list_key, [])
                 if int(entry[id_key]) not in have]
        if not fresh:
            continue
        if filename == RECIPE_FILENAME:
            # 配方号接着现有的往下数，别和已有的撞（撞了整份文件都不合法）。
            top = 0
            for entry in entries:
                try:
                    top = max(top, int(entry.get("id", 0)))
                except (TypeError, ValueError):
                    pass
            for offset, entry in enumerate(fresh, start=1):
                entry["id"] = top + offset
        added[filename] = fresh
        if not apply:
            continue
        merged = dict(raw)
        merged[list_key] = list(entries) + fresh
        # 存盘前必过校验：宁可什么都不写，也不要写出一份服务端读不了的文件。
        _SPECS[filename][0](merged)
        # 和管理页保存 / 数据备份拿同一把写锁：别在备份线程拷到一半时换掉文件。
        with write_lock(filename):
            shutil.copyfile(path, "%s.bak-%s"
                            % (path, time.strftime("%Y%m%d-%H%M%S")))
            write_json(path, merged)
    if apply and added:
        invalidate(data_dir)
    return added
