#: 哪些物品有「等级 / 角色限定」这两栏。
#:
#: ★ 判据是 **`part_flag != 0`（占装备槽）**，不是「铠甲和武器」这两个类别名
#:   —— 客户端在**穿的那一刻**才读这两个字段（`0x445817` 比等级、
