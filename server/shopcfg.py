#: ★★ 说明文里那些**固定的字**，一处定义。管理页要**实时**把同一句话画出来
#: （条件一改，popup 顶上立刻变），所以那边不得不自己拼一遍 ——
#: 但**词是这儿发过去的**（`/admin/api/catalog` 的 `card_phrases`），
#: 前端一个中文字都不写死。改这儿 = 两边同时改口。
CARD_PHRASES = {
    "any_mode": "任意模式",
    "mode_suffix": "模式",
    "head": "在%s中，",          # 在对战模式中，
    "tail": "时，获得一张%s。",   # 时，获得一张卡片。
    "card": "卡片",
    "off": "暂时无法获得",
    "bad": "条件无效",
    "is": "为",                  # 本局结果**为**胜利 / 通关
    "open": "（", "close": "）",  # 混用连接词时自己把括号写出来
}


def card_mode_text(rule):
    """规则那半句「算哪一局」：`在对战模式中，` / `在闯关模式「3 · …」（困难）中，`。"""
    mode = (rule or {}).get("mode")
    if mode in CARD_MODE_ZH:
        text = CARD_MODE_ZH[mode] + CARD_PHRASES["mode_suffix"]
    else:
        text = CARD_PHRASES["any_mode"]
    stage = (rule or {}).get("stage")
    if stage is not None:
        name = QUEST_ZH.get(stage)
        text += "「%s」" % ("%s · %s" % (stage, name) if name else stage)
    difficulty = (rule or {}).get("difficulty")
    if difficulty is not None:
        text += "%s%s%s" % (CARD_PHRASES["open"],
                            DIFFICULTY_ZH.get(difficulty, difficulty),
                            CARD_PHRASES["close"])
    return CARD_PHRASES["head"] % text


def card_condition_text(cond, with_scope=True):
    """一条条件念成人话：`一局内的命中率大于等于50%`。

    `with_scope=False` 时不写「一局内的 / 玩家累计」—— 整条规则的条件
    都在同一档时，前缀由调用方提到最前面只写一次（用户给的例子就是
    「一局内的命中率大于等于50%并且开枪数大于30」）。
    """
    cond = cond or {}
    metric = cond.get("metric")
    scope = cond.get("scope", CARD_SCOPE_MATCH)
    # ★ 带上角色（「左轮手枪（泰尔）击杀数」）—— 武器族本来就绑角色，
    #   说出来省得有人以为「用左轮」这条别的角色也够得着。
    label = card_metric_label(metric, cond.get("weapon"))
    head = CARD_SCOPE_PREFIX_ZH.get(scope, "") if with_scope else ""
    values = card_metric_values(metric)
    if values:
        # 枚举指标没有「大于等于 1」这种说法：**本局结果为胜利 / 通关**。
        want = cond.get("threshold")
        shown = str(want)
        for value, name in values:
            if value == want:
                shown = name
        return "%s%s%s%s" % (head, label, CARD_PHRASES["is"], shown)
    return "%s%s%s%s%s" % (head, label,
                           card_op_zh(cond.get("op", CARD_OP_GE), scope),
                           cond.get("threshold"), card_metric_unit(metric))


def card_conditions_text(conditions):
    """整串条件念成人话，**连接词混用时自己把括号写出来**。

    没有括号语法（用户拍板），所以求值就是**从上往下依次结合** ——
    `A 或者 B 并且 C` = `(A 或者 B) 并且 C`。只有一种连接词时不画括号
    （那时候括号只是噪音）。
    """
    conditions = list(conditions or ())
    if not conditions:
        return ""
    # 所有条件同一档统计范围 ⇒ 前缀提到最前面只写一次。
    scopes = set(cond.get("scope", CARD_SCOPE_MATCH) for cond in conditions)
    shared = CARD_SCOPE_PREFIX_ZH.get(conditions[0].get(
        "scope", CARD_SCOPE_MATCH), "") if len(scopes) == 1 else ""
    joins = set(cond.get("join", CARD_JOIN_AND) for cond in conditions[1:])
    mixed = len(joins) > 1
    text = card_condition_text(conditions[0], with_scope=not shared)
    for at, cond in enumerate(conditions[1:], start=1):
        # ★ 第二条不用套括号（那时候 `text` 还只是一条条件，套了是噪音）；
        #   从第三条起把**已经拼好的那一截**括起来，这正是「从上往下依次
        #   结合」那句话画出来的样子。
        if mixed and at >= 2:
            text = CARD_PHRASES["open"] + text + CARD_PHRASES["close"]
        text += CARD_JOIN_ZH.get(cond.get("join", CARD_JOIN_AND),
                                 CARD_JOIN_ZH[CARD_JOIN_AND])
        text += card_condition_text(cond, with_scope=not shared)
    return shared + text


def describe_card_rule(rule, card_name=None, with_tail=True):
    """一条获得规则念成一句人话。**全项目唯一的出处**（V0.3商店）。

        在对战模式中，一局内的命中率大于等于50%并且开枪次数大于等于30时，
        获得一张卡片。

    管理页那一行中间的说明、物品浮窗、游戏里的物品提示框（`item_desc_zh`）、
    三方合并的冲突提示（`cfgmerge.label_of`）都念它 —— 各写一遍的话，
    改了条件之后总有一处还在说旧话。

    ★ `with_tail=False` 砍掉末尾那句「时，获得一张卡片。」：**游戏里的
    提示框**就是停在那张卡上弹出来的，前面又已经写着「获得条件：」——
    再说一遍「获得一张卡片」纯属占那 234 px 的宽度（`ITEM_DESC_MAX_LINES`
    只有 5 行，`test_cards` 按字数卡着一道软上限）。

    ⚠ **结果里绝不能出现 `|`** —— 客户端拿它当说明的分段符
    （`wcstok`，`0x5fa904`），混进去会把一段说明拦腰切开。
    """
    if not isinstance(rule, dict):
        return ""
    if not rule.get("listed"):
        return CARD_PHRASES["off"]
    body = card_conditions_text(rule.get("conditions"))
    if not body:
        # 一条条件都没有 = 这条规则说不出「什么时候给」，画面上同样显示这句。
        return CARD_PHRASES["bad"]
    text = card_mode_text(rule) + body
    if with_tail:
        # ★ `card_name` 不给 = 调用方**已经知道说的是哪张卡**。
        text += CARD_PHRASES["tail"] % (
            ("「%s」" % card_name) if card_name else CARD_PHRASES["card"])
    # 段分隔符绝不能混进正文（见 docstring）。名字是运营改的，真有可能带。
    return text.replace(DESC_SEPARATOR, "/")


#: ★ 客户端把说明按 `|` 切开，**实际只画前 2 段**（`0x45c4c9` / `0x455534` /
#: `0x45ff65` 都是循环**顶部**的 `cmp i,2 / je 出口`，`i` 只取 0 和 1；
#: 第 3 个标签 `ItemInfo2Txt` 根本不参与切分，它画的是「买了到手的东西」那行绿字）。
#:
#:   第 1 段 `ItemInfo0Txt` 234×82 px ≈ 6 行  ← 数值
#:   第 2 段 `ItemInfo1Txt` 232×45 px ≈ 3 行  ← 特殊效果 / 用途
#:
#: 各留一行余量。段内换行用 `\n`。
#: ⚠ **说明里绝对不能出现裸 `|`** —— 它被 `wcstok`（`0x5fa904`）当分隔符吃掉。
ITEM_DESC_MAX_LINES = 5
ITEM_DESC_MAX_LINES_2 = 3

#: 说明的段分隔符（客户端 `0x668274` 就是这个字符）。
DESC_SEPARATOR = "|"

#: 卡片说明里「这张卡能合成什么」那几行的行首（用户 2026-09-13）。
#:
#: ★ 原来是一个光秃秃的 `➜` —— 看的人得**猜**它是「合成」还是「变成」还是
#:   「兑换」。和上一行「获得条件：」一样写成一个词，一眼就分得出
#:   「这张卡怎么来」和「这张卡能去哪」。
CARD_CRAFT_PREFIX = "可合成："

#: 压行：数值加成一行最多摆几项。234 px / 字号 10 大约放得下 3 项
#: （「攻击 +3%　防御 +2%　生命 +2」）。★ 这个数要实机核对。
BONUS_PER_LINE = 2
# 每一项字段固定宽度10
BONUS_PER_WIDTH = 10

def _weapon_lines(weapon):
    """武器数值那几行。`weapon` 是 `shop_items.json` 里那个 dict。"""
    lines = []
    damage = weapon.get("damage")
    if damage is not None:
        lines.append("伤害 %d " % damage)
        # 伤害按**部位**分档，没有随机数（§17）。爆头 / 腿部两档不一定都有。
        if weapon.get("head_damage"):
            lines.append("爆头 %d " % weapon["head_damage"])
        # if weapon.get("legs_damage"):
        #     lines.append("腿部 %d" % weapon["legs_damage"])
    # ★ 溅射两格原来一直没画出来 —— 榴弹类真正的杀伤在这
    if weapon.get("splash_damage"):
        lines.append("溅射 %d " % weapon["splash_damage"])
    if weapon.get("splash_range"):
        lines.append("溅射范围 %d " % weapon["splash_range"])
    if weapon.get("magazine"):
        lines.append("弹容 %d " % weapon["magazine"])
    if weapon.get("cooling_ms"):
        lines.append("射速 %.1f/秒 " % (1000.0 / weapon["cooling_ms"]))
    if weapon.get("reload_ms"):
        lines.append("装填 %.1f秒 " % (weapon["reload_ms"] / 1000.0))
    if weapon.get("velocity"):
        lines.append("飞行速度 %d " % weapon["velocity"])
    aligned = []

    for i in range(0, len(lines), BONUS_PER_LINE):
        chunk = lines[i:i + BONUS_PER_LINE]
        # 每一项左对齐，补空格到固定宽度
        padded = [item.ljust(BONUS_PER_WIDTH) for item in chunk]
        aligned_line = "".join(padded)
        aligned.append(aligned_line)
    return aligned


def _bonus_lines(bonus):
    """数值加成压成一行最多 `BONUS_PER_LINE` 项。"""
    cells = []
    for key in BONUS_ORDER:
        value = bonus.get(key)
        label = BONUS_ZH.get(key)
        if not value or label is None:
            continue
        cells.append("%s %+d%s" % (label[0], value, "%" if label[1] else ""))
    return ["　".join(cells[i:i + BONUS_PER_LINE])
            for i in range(0, len(cells), BONUS_PER_LINE)]


def _effect_lines(item):
    """第 2 段：特殊效果 / 条件加成 / 「无属性加成」兜底。"""
    lines = []
    # 按部位生效的（翅膀滑翔）。★ 放在最前面：它是这件东西**唯一**的效果，
    #   而且没有它的话这几件会掉进 `KIND_USAGE_ZH["armor"]` 的「无属性加成」
    #   兜底 —— 那句话对翅膀是**错的**，玩家照着看就以为纯外观。
    # ★ **按位与，不是相等**：`0x55850e and eax,[esp+4]` —— 客户端测的是位。
    #   一件东西可以同时占好几个槽（「羽翼套装」`PartFlag=539` = 512+16+8+2+1，
    #   上衣/下装/鞋/手套/翅膀一件全占），写成 `== 512` 的话**恰恰是套装漏掉**，
    #   而用户报的就是穿套装时感觉不一样。
    for flag, text in sorted(PART_EFFECT_ZH.items()):
        if item.part_flag & flag:
            lines.append(text)
    hardcoded = SPECIAL_EFFECT_BY_ID.get(item.id)
    if hardcoded:
        lines.append(hardcoded % ())
    for key, value in sorted((item.bonus or {}).items()):
        if key in DEAD_BONUS_KEYS or not value:
            continue
        template = SPECIAL_BONUS_ZH.get(key)
        if template is not None:
            lines.append(template % value)
    if item.bonus_lua:
        text = BONUS_LUA_ZH.get(item.id)
        # 翻不出来的条件加成只提一句 —— 客户端自己会算，服务端解释不了。
        lines.append(text % () if text else "（附带条件加成）")
    return lines


#: 「现取」的记号：`item_desc_zh` 的可选参数留空时自己去读配置。
#: ★ 默认现取而**不靠调用方记得传** —— 判据要落在结果上，不落在
#:   「谁记得加那句」上（同 `admin.js` 的 `lockList()`）。漏传的症状是
#:   「就是没人看得到，一句报错都没有」，正是铁律 13 说的那一类。
#:   热路径想省掉重复 `os.stat` 的调用方可以把读好的表传进来 ——
#:   那是**优化**，不是**契约**。
_AUTO = object()


def title_effect_zh(item_id):
    """一个称号的**加成效果**压成一句话；查不到就空串（V0.3商店）。

    ★ 出处仍旧是 `item_desc_zh()` 那一套（`_bonus_lines` 数值 +
    `_effect_lines` 特效 / Lua / exe 硬编码的三条）—— 卡片提示框上
    「合成出来是干什么的」和穿上身之后提示框里写的**必须是同一句话**。
    """
    item = shopdata.get(item_id)
    if item is None:
        return ""
    bits = _bonus_lines(item.bonus or {}) + _effect_lines(item)
    return "　".join(line.replace("\n", " ") for line in bits if line)


def card_recipes(item_id, recipes_table):
    """用得上这张卡片的**上架配方**，按产物 id 排好。

    ★ 一张卡片**可以对应好几个称号**（运营配得出来），一个称号也**可以要
    好几种卡片** —— 两种情况都要说得出来，所以这儿返回的是整条配方，
    由调用方决定怎么念。
    """
    out = []
    for recipe in recipes_table or ():
        if not recipe.get("listed"):
            continue
        for slot in recipe.get("materials") or ():
            try:
                if int(slot.get("id", 0)) != int(item_id):
                    continue
            except (TypeError, ValueError):
                continue
            out.append((recipe, int(slot.get("count", 1))))
            break
    out.sort(key=lambda pair: int(pair[0].get("result", 0)))
    return out


def _recipe_cost_zh(recipe, item_id):
    """一条配方的代价念成一句：「幸运卡片×500 + 100000 金币」。

    ★ **把每一种材料都写出来** —— 一个称号要好几种卡片时，只写「500 张」
    会让人以为攒够这一种就合得出来（用户 2026-09-13 点的正是这一条）。
    本卡片排在最前面，别的材料跟在后面。
    """
    bits = []
    for slot in recipe.get("materials") or ():
        try:
            mid, count = int(slot.get("id", 0)), int(slot.get("count", 1))
        except (TypeError, ValueError):
            continue
        name = item_name(mid) or ("#%d" % mid)
        bits.append(("%s×%d" % (name, count), mid == int(item_id)))
    bits.sort(key=lambda pair: 0 if pair[1] else 1)
    text = " + ".join(name for name, _mine in bits)
    cost = int(recipe.get("cost", 0) or 0)
    if cost:
        text = (text + " + " if text else "") + "%d 金币" % cost
    return text


def _card_desc_lines(item, card_rules, recipes_table):
    """卡片提示框那两段：**怎么拿** + **合成出来是什么、要什么**（V0.3商店）。

    返回 `(第1段的行, 第2段的行)`，不是卡片就是 `([], [])`。

    ★ 游戏里和管理页**同一个出处** —— 这个函数的结果经 `item_desc_zh`
    进 `ItemInfo +0x18`（客户端提示框下半）和管理页 catalog 的 `desc`
    （`paintTip` 已经会按 `|` 分段、按 `\\n` 换行地画）。

    ★★ **两段都是现算的** ⇒ 运营改完条件 / 改完配方，说明跟着变；
    **没有配方就不写那一段**（用户 2026-09-13）。

    ★ **两段是按行数预算分的**（第 1 段 ≈5 行、第 2 段 ≈3 行，§31）：

        第 1 段  获得条件（1 行）+ 每个称号一行「可合成：[叫什么] 要什么」
        第 2 段  每个称号的**加成效果**，一行一个，**行首是称号名**

    一张卡片能合成好几个称号时两段一起长，各自按预算截断并在末尾写
    「…另有 N 个」。默认的一一对应下是 2 行 + 1 行，很宽裕。
    """
    rule = None
    for entry in card_rules or ():
        if entry.get("card") == item.id:
            rule = entry
            break
    if rule is None:
        return [], []
    # 名字和末尾那句「获得一张卡片」都不要 —— 提示框就是停在那张卡上弹出来
    # 的，前面还写着「获得条件：」，再说一遍纯占宽度（见 `describe_card_rule`）。
    how = describe_card_rule(rule, with_tail=False)
    stats = ["获得条件：" + how] if how else []
    pairs = card_recipes(item.id, recipes_table)
    if not pairs:
        return stats, []
    shown = []
    room = max(1, ITEM_DESC_MAX_LINES - len(stats))
    for recipe, _mine in pairs:
        if len(shown) >= room:
            break
        title = item_name(recipe["result"]) or ("#%s" % recipe["result"])
        shown.append((title, title_effect_zh(recipe["result"])))
        stats.append("%s%s　%s"
                     % (CARD_CRAFT_PREFIX, title,
                        _recipe_cost_zh(recipe, item.id)))
    left = len(pairs) - len(shown)
    if left > 0:
        # 放不下的那些至少要说一声有 —— 不说的话玩家会以为只有这几个。
        stats[-1] = ("%s…另有 %d 个称号用得上它（详见合成界面）"
                     % (CARD_CRAFT_PREFIX, left + 1))
        shown.pop()
    notes = []
    #: ★ **每个效果前都写称号名，只有一个时也写**（用户 2026-09-13）：
    #:   不写名字的那一行看上去像是**卡片自己**的效果，而卡片穿不上身、
    #:   本来就没有效果 —— 名字才是「这是合出来那个称号的效果」的标记。
    for title, effect in shown[:ITEM_DESC_MAX_LINES_2]:
        if not effect:
            continue
        notes.append("%s　%s" % (title, effect))
    return stats, notes


def item_desc_zh(item, card_rules=_AUTO, recipes_table=_AUTO, weapons_table=None):
    """物品说明。**从本地数据现算**，原版那份说明随服务端 DB 一起没了。

    ⚠ 这不是「发明玩法」（铁律 12）—— 里面每个数都是客户端**自己也查得到**
    的（武器数值来自 `weapon.ini`、装备加成来自 `EquipBonus-Chn.ini`、
    特效的语义来自 14 个 `GetEquipBonus` 调用点），只是原版把它们写在服务端
    下发的说明里，我们照着重新拼一遍。

    分两段（中间一个 `|`，客户端画成上下两块）：

        第 1 段  武器数值 / 装备加成 —— 同类压在一行上
        第 2 段  特殊效果 / 条件加成 / 「无属性加成」

    两段都空就返回空串；只有第 2 段有内容时**不发 `|`**（省得切出一个空段）。

    ★★ **称号卡片是唯一一类「材料」也带说明的**（V0.3商店，用户 2026-09-13）：
    第 1 段写**获得条件**、第 2 段写**能合成什么称号** —— 两句都来自运营配置，
    所以改完保存即刻生效。⚠ 已经在线的玩家要**重新登录**才看得到新说明：
    客户端把物品定义缓存住了（「发过就记成已请求，不回就再也不问了」，
    packet_api §3.9）。
    """
    if item is None:
        return ""
    stats = []
    notes = _effect_lines(item)
    if item.weapon:
        weapon = item.weapon
        if item.kind == "weapon":
            # ★ X3：武器的第 2 段可以由管理页配置（`weaponcfg`，任何武器）；
            #   自定义武器的数值行画的是**对战（PVP）那一套有效值**，并在第 1 段
            #   首行加一句「仅显示PVP属性…」（用户 2026-09-19，提示框装不下两套）。
            #   `import` 写在函数里：`weaponcfg` 顶层 `import shopcfg`，别绕成环。
            import weaponcfg
            if weapons_table is None:
                weapons_table = weaponcfg.load()
            if getattr(item, "custom", False):
                weapon = weaponcfg.effective_weapon_dict(item, weaponcfg.MODE_PVP, weapons_table)
                stats.append(weaponcfg.PVP_ONLY_NOTE)
            custom_desc = weaponcfg.desc_of(item.id, weapons_table)
            if custom_desc:
                notes = custom_desc.split("\n")
        stats.extend(_weapon_lines(weapon))
    stats.extend(_bonus_lines(item.bonus or {}))
    if not stats and not notes and item.kind == "material":
        if card_rules is _AUTO:
            card_rules = cards()[0]
        if recipes_table is _AUTO:
            recipes_table = recipes()[0]
        stats, notes = _card_desc_lines(item, card_rules, recipes_table)
    if not stats and not notes:
        # 一条加成都查不到 —— 按类别写用途，让玩家分得清「真没有」和「漏写了」
        usage = KIND_USAGE_ZH.get(item.kind)
        if not usage:
            return ""
        notes = [usage]
    if not notes:
        return "\n".join(stats[:ITEM_DESC_MAX_LINES])
    notes = "\n".join(notes[:ITEM_DESC_MAX_LINES_2])
    if not stats:
        return notes
    return "\n".join(stats[:ITEM_DESC_MAX_LINES]) + DESC_SEPARATOR + notes


