def write_json(path, data):
    """原子写：tmp → fsync → replace（和 `account_store._write_unlocked` 同款）。

    ★ `newline="\\n"`：铁律 3 要求 `.json` 一律 LF 无 BOM
    （服务端包要在 Linux 上跑）。
    """
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    tmp = "%s.%d.tmp" % (path, os.getpid())
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as fp:
            json.dump(data, fp, ensure_ascii=False, indent=2)
            fp.write("\n")
            fp.flush()
            os.fsync(fp.fileno())
        atomicfile.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except OSError:
                pass


def ensure_files(data_dir=None):
    """五份配置不存在就生成，**已存在一律不覆盖**（D7）。返回新建了哪几个。

    ★ 这是**唯一会自动生成**这几份文件的地方。云上升级时用户手改过的价格 /
    配方 / 掉落必须原样留着 —— 覆盖它们等于把运营数据抹了（铁律 11）。
    另外只有两个写入点，都是用户**主动**按的：管理页的保存按钮
    （`web/admin.py`，存盘前必过 `validate_*`）和管理页「数据备份」的回滚
    （`databackup.restore`，写盘前同样过今天的 `validate_*`）。
    除此之外谁都不许写。
    """
    created = []
    for filename, (_validate, build, _empty) in _SPECS.items():
        path = path_of(filename, data_dir)
        if os.path.exists(path):
            continue
        write_json(path, build())
        created.append(filename)
    if created:
        invalidate(data_dir)
    return created


