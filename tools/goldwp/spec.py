#: 客户端 `0x40a138` 的武器 Id 解码器，原样照抄（§41）。返回 `(系列, 索引)`。
#: `weapon_slot_index()` 必须等于槽位，否则弹药数组越界 —— `test_weaponini` 拿它守着。
def decode_weapon_id(weapon_id):
    """照 `0x40a138` 原样实现：系列 = Id%10，索引 = (Id/10)%100，D/R/F 系再归一化成槽位。"""
    series = weapon_id % 10
    index = (weapon_id // 10) % 100
    if 3 <= series <= 5 and index < 50:
        index %= 10
    return series, index


def weapon_slot_index(weapon_id):
    """客户端拿来下标弹药数组的那个索引。"""
    return decode_weapon_id(weapon_id)[1]

