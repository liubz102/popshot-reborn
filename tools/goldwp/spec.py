#: 原版 `weapon.ini`（CP949 + CRLF，221519 B）的哈希。`2245b8c7^` 那份 == `main/Pack_decrypt` 那份。
#: ★ 放在这个**只依赖标准库**的模块里：`test/test_weaponini.py` 要拿它核对，而 `build.py`
