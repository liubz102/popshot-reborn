def read_weapon_ini(path=None):
    """`weapon.ini` → `OrderedDict{节名: OrderedDict{键: 值}}`，**保留 `#` 注释键**
    （`#CoolingTime=2000` 这种原版注释掉的行原样带走，客户端本来就当它不存在）。
    编码走 `tools/weapondata.read_ini` 同一套嗅探。"""
    import importlib.util
    spec = importlib.util.spec_from_file_location("goldwp_weapondata",
                                                  os.path.join(TOOLS, "weapondata.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    path = path or os.path.join(develop_root(), "Data", "weapon.ini")
    with open(path, "rb") as fp:
        raw = fp.read()
    if raw[:2] == b"\xff\xfe":
        text = raw.decode("utf-16le", "replace")
    else:
        try:
            text = raw.decode("cp949")
        except UnicodeDecodeError:
            text = raw.decode("cp936", "replace")
    sections = collections.OrderedDict()
    current = None
    for line in text.splitlines():
        line = line.strip().lstrip("﻿")
        if not line or line.startswith(";"):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1].strip()
            sections[current] = collections.OrderedDict()
            continue
        if current is None or "=" not in line:
            continue
        key, value = line.split("=", 1)
        sections[current][key.strip()] = value.strip()
    return sections


def d3_sections(sections):
    """`{自定义小节名: 参考小节的字段表}`，9 主 + 2 子。"""
    out = collections.OrderedDict()
    for w in WEAPONS:
        out[w.custom_section] = sections[w.section]
        if w.piece_section:
            out[w.custom_piece_section] = sections[w.piece_section]
    return out


_D3 = re.compile(r"D3", re.IGNORECASE)


def rename(stem):
    """资源文件名里的 `D3` → `C`；没有 `D3` 的（原版笔误 / 共用件）在末尾加 `_C`。"""
    if _D3.search(stem):
        return _D3.sub(SERIES, stem, count=1)
    return stem + "_" + SERIES


def weapon_by_section(name):
    for w in WEAPONS:
        if w.section.lower() == name.lower() or (w.piece_section and w.piece_section.lower() == name.lower()):
            return w
    raise KeyError(name)
