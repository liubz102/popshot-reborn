"""spec.py —— 自定义武器的**清单**：谁参考谁、新编号是什么、资源改什么名（X_Mod · X3 / X6）。

`preview.py`（效果图）和 `build.py`（实装）都从这里取数，别在两边各抄一份。

## 两批（`BATCHES`）

| 批次 | 母本 | 配色 | 部位码 | 武器 Id | 中文名 |
|---|---|---|---|---|---|
| `C` | 爆裂 3（`D3`）| 黄金 + 银白 | 92 | `1 0 0C 3 S 5` | 「xxx 自定义1」|
| `P` | 复合 3（`F3`）| 粉 + 绿 | 93 | `1 0 0C 4 S 5` | 「xxx 自定义2」|

★ `WEAPONS` 是**两批拼起来的 18 条**，不是某一批 —— `build.py` / `test_weaponini.py`
里所有 `for w in WEAPONS` 因此自动覆盖全部批次，加第三批也不用改那些循环。
★ `WEAPONS[0].item_id` 必须一直是 `1920001`：`tools/openweapons.py` 的 `GOLDWP_ANCHOR`
钉着它（那 18 件原版 3 级武器插在本块**之前**），`test_openweapons` 守着这条位置关系。

编号口径：

    物品 id   X <部位码> 000 S    X = 角色 1/2/3，S = 槽位 1/2/3   → 1920001… / 1930001…
    武器 Id   1 0 0C T S E        C = 角色 0/1/2，S = 槽位          → 1000315… / 1000415…
                                  T = 档位（原版 0/1/2），E = 系列位（D=5 / R=3 / F=4）
    子弹药 Id 1 0 0C 5 T E        只有泰尔 / 卡希尔的 2 号有        → 1000535 / 1000545

★★ 武器 Id 不是随便编的，客户端会**拆数位**（§41 / D31）：
    系列 = Id % 10；索引 = (Id / 10) % 100；若 3 ≤ 系列 ≤ 5 且 索引 < 50 则 索引 %= 10。
    这个索引直接拿去下标**只有 4 格**的弹药数组，而且三个调用点都**只查 >= 0、不查上界**。
    ⇒ 新编号必须满足「系列 ∈ [3,5] 且 档*10+槽 < 50」，否则索引越界：
      既永远不换弹（把堆里的指针当弹药数），又每开一枪往堆里乱写一个 dword。
    初版用的 `1 0 0C 9 S 0`（档 9、系列 0）正好两条都踩，实机表现是
    「自定义武器无限开火 + 结算界面卡死」。**别再把档改回 ≥ 5 或把系列改出 [3,5]。**
    ⚠ 合法组合只有 `档 ∈ {0..4} × 系列 ∈ {3,4,5}` 共 15 个：原版占 9 个、C 占 (3,5)、
      P 占 (4,5)，**只剩 4 个**。第三批必须改系列位（档已经用到头了）。

    手持网格  chNN W 0<系><档><槽>    C 是 014S（爆裂 3 的 013S）、P 是 034S（复合 3 的 033S）
    3D 弹体   chNN D 0<系><档>2      同上，只有泰尔 / 卡希尔的 2 号
    amf 条目  CHnn_WPk_<字母>        母本是 CHnn_WPk_D3 / _F3（有 …W 的再加一条，指同一张图）
    HUD 图集  Wp0k<字母>             母本是 Wp0kD3 / Wp0kF3，3 帧 = 3 个角色
    商店图标  무기_<韩文名> <字母>     母本是 무기_<韩文名> D3 / F3
    ini 小节  [chNN-0S<字母>]        Name = <韩文名> <字母>
"""
