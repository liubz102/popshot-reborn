#: ★ 两批拼起来的 18 条。顺序 = `BATCHES` 的顺序，`WEAPONS[0]` 必须是 `1920001`（见文件头）。
WEAPONS = tuple(w for b in BATCHES.values() for w in _rows(b))


def batch_of(weapon):
    """一把武器属于哪个批次。"""
    return BATCHES[weapon.batch]


def weapons_of(letter):
    """某一批的 9 条。"""
    return tuple(w for w in WEAPONS if w.batch == letter)


#: 客户端 `0x40a138` 的武器 Id 解码器，原样照抄（§41）。返回 `(系列, 索引)`。
#: `weapon_slot_index()` 必须等于槽位，否则弹药数组越界 —— `test_weaponini` 拿它守着。
def decode_weapon_id(weapon_id):
    """照 `0x40a138` 原样实现：系列 = Id%10，索引 = (Id/10)%100，D/R/F 系再归一化成槽位。"""
    series = weapon_id % 10
    index = (weapon_id // 10) % 100
    if 3 <= series <= 5 and index < 50:
        index %= 10
    return series, index


def weapon_slot_index(weapon_id):
    """客户端拿来下标弹药数组的那个索引。"""
    return decode_weapon_id(weapon_id)[1]

