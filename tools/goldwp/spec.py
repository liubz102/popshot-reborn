#: 追加块的第一行。客户端的 ini 读取器把 `;` 开头当注释（原版 ini 里就有 `;` 行）。
#: ★ **只有这一个标记**：两批的小节写在同一块里（`build.py` 砍掉标记之后的一切再整块重写）。
