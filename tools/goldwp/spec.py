def rename(stem, weapon_or_batch):
    """资源文件名里的母本系列（`D3` / `F3`）→ 批次字母；没有的（原版笔误 / 共用件）在末尾加 `_<字母>`。

    ★ 正则必须是整个 `D3` / `F3` 两个字符，**不能只写 `F`** —— 复合 3 的 efx 大量引用
      `CH00_Wp01F1_*.dds` / `*F2_*.dds` 这类跨档共用的贴图，只匹配 `F` 会把它们一起改名、撞名。
    """
    batch = weapon_or_batch if isinstance(weapon_or_batch, Batch) else batch_of(weapon_or_batch)
    pattern = re.compile(re.escape(batch.src_stem), re.IGNORECASE)
    if pattern.search(stem):
        return pattern.sub(batch.letter, stem, count=1)
    return stem + "_" + batch.letter


def weapon_by_section(name):
    """按母本小节名或子弹药小节名找武器。★ 两批的母本不同，所以不会歧义。"""
    for w in WEAPONS:
        if w.section.lower() == name.lower() or (w.piece_section and w.piece_section.lower() == name.lower()):
            return w
    raise KeyError(name)
